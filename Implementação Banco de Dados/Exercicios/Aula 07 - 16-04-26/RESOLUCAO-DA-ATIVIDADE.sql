-- Listar todos os livros cadastrados
SELECT * FROM LIVRO;

-- Listar o nome do aluno, o nome do livros a data do empréstimo de todos os alunos que não tem data de devolução
SELECT
	ALUNO.NOME AS NOME_ALUNO,
    LIVRO.TITULO,
    EMPRESTIMO.DT_EMPRESTIMO
FROM
	ALUNO
    INNER JOIN EMPRESTIMO ON
    EMPRESTIMO.IDALUNO = ALUNO.IDALUNO
    INNER JOIN LIVRO ON
    LIVRO.IDLIVRO = EMPRESTIMO.IDLIVRO
WHERE
	EMPRESTIMO.DT_DEVOLUCAO IS NULL;


