-- CONECTANDO AO BANCO DE DADOS DO EXERCICIO 15.
-- LISTAR TODOS OS ALUNOS CADASTRADOS.
SELECT * FROM ALUNO;

-- LISTAR TODOS OS CRUSOS CADASTRADOS.
SELECT * FROM CURSO;

-- LISTAR A DISCIPLICA DO LUCAS
SELECT
	ALUNO.NOME,
    ALUNO.EMAIL,
    CURSO.NOME
FROM
	ALUNO
    INNER JOIN MATRICULA ON
    ALUNO.IDALUNO = MATRICULA.IDALUNO
    INNER JOIN CURSO ON
    CURSO.IDCURSO = MATRICULA.IDCURSO
WHERE
	ALUNO.NOME LIKE 'LUCAS%';
    
    
-- SELECIONAR TODOS OS CAMPOS
SELECT
	MATRICULA.IDMATRICULA,
    MATRICULA.DT_MATRICULA,
    ALUNO.IDALUNO,
    ALUNO.NOME,
    ALUNO.EMAIL,
    CURSO.IDCURSO,
    CURSO.NOME,
    CURSO.CARGA_HORARIA
FROM
	ALUNO
    INNER JOIN MATRICULA ON
    MATRICULA.IDALUNO = ALUNO.IDALUNO
    INNER JOIN CURSO ON 
    CURSO.IDCURSO = MATRICULA.IDCURSO;
    
-- LISTAR TODOS OS ALUNOS NO CURSO DE BANCO DE DADOS
SELECT
	ALUNO.NOME,
    ALUNO.EMAIL
FROM
	ALUNO
    INNER JOIN MATRICULA ON
    MATRICULA.IDALUNO = ALUNO.IDALUNO
    INNER JOIN CURSO ON
    CURSO.IDCURSO = MATRICULA.IDCURSO
WHERE
	CURSO.NOME = 'BANCO DE DADOS RELACIONAL';
    
