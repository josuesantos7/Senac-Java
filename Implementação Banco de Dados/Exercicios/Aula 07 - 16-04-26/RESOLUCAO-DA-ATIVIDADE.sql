-- SELECIONANDO O BANCO DE DADOS 14.
USE DBEXERCICIO14;

-- ############################
-- LISTAR TODOS OS PROFESSORES.
SELECT * FROM PROFESSOR;


-- #############################
-- LISTAR O NOME SOMENTE DO PROFESSOR DE MATEMÁTICA.
SELECT
	NOME
FROM
	PROFESSOR
WHERE
	DISCIPLINA = 'MATEMATICA';


-- #############################
-- LISTAR O NOME E DISCIPLINA DO PROFESSOR DA TURMA 2A.
SELECT
	PROFESSOR.NOME,
    PROFESSOR.DISCIPLINA,
    TURMA.NOME
FROM
	PROFESSOR
    inner join TURMA ON
    PROFESSOR.IDPROFESSOR = TURMA.IDPROFESSOR
WHERE
	TURMA.NOME = '2A';


-- #############################
-- LISTAR QUASE TODOS OS DADOS.
SELECT
	TURMA.IDTURMA,
    TURMA.NOME AS NOME_TURMA,
    PROFESSOR.IDPROFESSOR,
    PROFESSOR.NOME AS NOME_PROFESSOR,
    PROFESSOR.DISCIPLINA
FROM
	PROFESSOR
    INNER JOIN TURMA ON
    PROFESSOR.IDPROFESSOR = TURMA.IDPROFESSOR;
    
    

